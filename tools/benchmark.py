"""Reproducible benchmark suite (design spec §19, 59).

Measures, with a live R worker:
  * worker startup
  * scalar round trips (Python -> R -> Python)
  * DataFrame transfer at 1k / 100k / 1M rows, JSON vs Arrow IPC, both directions
  * numpy array transfer (1e6 doubles)
  * proxy method call latency (coef(lm))
  * plot return

Writes docs/benchmarks.md with hardware / software metadata.  Nothing else
ever writes that page.  Run: python tools/benchmark.py [--rows 1000,100000,1000000]
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import platform
import statistics
import sys
import time

import numpy as np
import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def timeit(fn, repeat=5):
    ts = []
    for _ in range(repeat):
        t = time.perf_counter()
        fn()
        ts.append(time.perf_counter() - t)
    return statistics.median(ts), min(ts)


def frame(n: int) -> pd.DataFrame:
    rng = np.random.default_rng(0)
    return pd.DataFrame({"id": np.arange(n), "x": rng.normal(size=n), "g": pd.Categorical(rng.choice(["a", "b", "c"], n)),
                         "t": pd.date_range("2020-01-01", periods=n, freq="min"), "s": rng.choice(["alpha", "beta", "gamma"], n)})


def main() -> None:
    import rpython as rp
    ap = argparse.ArgumentParser()
    ap.add_argument("--rows", default="1000,100000,1000000")
    ap.add_argument("--repeat", type=int, default=5)
    a = ap.parse_args()
    rows = [int(x) for x in a.rows.split(",")]
    results: list[tuple[str, str]] = []

    t = time.perf_counter()
    r = rp.RSession(timeout=None)
    results.append(("R worker startup", f"{time.perf_counter() - t:.2f} s"))

    med, best = timeit(lambda: r("1 + 1"), a.repeat * 4)
    results.append(("scalar call r('1 + 1')", f"{med * 1000:.1f} ms median ({best * 1000:.1f} ms best)"))
    med, _ = timeit(lambda: r.assign("x", 41), a.repeat * 4)
    results.append(("scalar assign", f"{med * 1000:.1f} ms median"))

    for n in rows:
        df = frame(n)
        mem = df.memory_usage(deep=True).sum() / 1e6
        for mode in ("json", "arrow"):
            if mode == "json" and n > 100_000:
                continue
            rp.config(transfer=mode)
            try:
                med_up, _ = timeit(lambda: r.assign("df", df), max(2, a.repeat // 2))
                med_down, _ = timeit(lambda: r.get("df"), max(2, a.repeat // 2))
                back = r.get("df")
                ok = back.equals(df)
                results.append((f"DataFrame {n:,} rows ({mem:.1f} MB) via {mode}",
                                f"py->R {med_up:.3f} s, R->py {med_down:.3f} s, round trip {'lossless' if ok else 'DIFFERS'}"))
            except Exception as e:  # noqa: BLE001
                results.append((f"DataFrame {n:,} rows via {mode}", f"failed: {e}"))
        rp.reset_config()

    arr = np.random.default_rng(1).normal(size=1_000_000)
    med_up, _ = timeit(lambda: r.assign("arr", arr), max(2, a.repeat // 2))
    med_down, _ = timeit(lambda: r.get("arr"), max(2, a.repeat // 2))
    results.append(("numpy 1e6 doubles (Arrow)", f"py->R {med_up:.3f} s, R->py {med_down:.3f} s"))

    fit = r("lm(mpg ~ wt, data = mtcars)")
    med, _ = timeit(lambda: fit.coef(), a.repeat * 2)
    results.append(("proxy method call fit.coef()", f"{med * 1000:.1f} ms median"))
    med, _ = timeit(lambda: r.eval("plot(1:10)"), a.repeat)
    results.append(("plot return (PNG)", f"{med * 1000:.0f} ms median"))

    caps = r.capabilities
    r.close()
    import importlib.metadata as md
    lines = ["# Benchmarks", "",
             f"Generated by `python tools/benchmark.py` on {dt.datetime.now().isoformat(timespec='minutes')}.", "",
             "## Environment", "",
             f"* Platform: {platform.platform()} ({platform.machine()}), {os.cpu_count()} CPUs",
             f"* Python {platform.python_version()}; pandas {md.version('pandas')}, numpy {md.version('numpy')}, pyarrow {md.version('pyarrow') if _has('pyarrow') else 'absent'}",
             f"* R {caps.get('r_version')} ({caps.get('platform')}); arrow: {'yes' if caps.get('arrow') else 'no'}",
             f"* Transport: stdio JSON + Arrow IPC files in a temp directory; repeats: {a.repeat} (median reported)", "",
             "## Results", "", "| Benchmark | Result |", "|---|---|"]
    lines += [f"| {k} | {v} |" for k, v in results]
    lines += ["", "## Method", "",
              "Each timing wraps the public API call (`r.assign`, `r.get`, `r(...)`, proxy method) with `time.perf_counter()`; the median of the repeats is reported. ",
              "Round-trip results are checked with `DataFrame.equals` after each transfer. No comparison with other tools is made here: ",
              "embedded bridges (rpy2, reticulate) have lower per-call latency by design; RPython trades a few milliseconds per call for process isolation and symmetry. ",
              "Re-run the script on your hardware before quoting numbers."]
    out = os.path.join(ROOT, "docs", "benchmarks.md")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("\n".join(lines))
    print("\nwrote", out)


def _has(p: str) -> bool:
    import importlib.util
    return importlib.util.find_spec(p) is not None


if __name__ == "__main__":
    main()
